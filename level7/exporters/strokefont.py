CAP_RATIO = 0.657     # cap height / text height (GRAFIS PLT)
ADVANCE_RATIO = 0.857  # character advance / text height (GRAFIS PLT)


def text_strokes(text: str, position, height: float, rotation_deg: float = 0.0):
    """Return polylines (marker coordinates, mm) drawing ``text``. Unknown characters are skipped
    (e.g. Arabic): the caller should report them."""
    s = CAP_RATIO * height / 6.0
    adv = ADVANCE_RATIO * height
    a = math.radians(rotation_deg)
    c, si = math.cos(a), math.sin(a)
    out = []
    for i, ch in enumerate(text.upper()):
        for stroke in G.get(ch, []):
            pts = []
            for gx, gy in stroke:
                x, y = i * adv + gx * s, gy * s
                pts.append((position[0] + c * x - si * y, position[1] + si * x + c * y))
            out.append(pts)
    return out


def unsupported_chars(text: str) -> set[str]:
    return {ch for ch in text.upper() if ch not in G}
